/* ── Вспомогательное ── */
function mmss(sec) {
  var m = Math.floor(sec / 60), s = sec % 60;
  return m + ':' + (s < 10 ? '0' + s : s);
}

/* Нормализация для программной проверки цитат: цитата обязана найтись в транскрипте,
   иначе промт объявляет вердикт по этому пункту недействительным. */
function normalizeQuote(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[«»"',.!?…—–\-()]/g, ' ')
    .replace(/ё/g, 'е')
    .replace(/\s+/g, ' ')
    .trim();
}

var TRANSCRIPT_NORM = TRANSCRIPT.map(function (r) {
  return { t: r.t, who: r.who, norm: normalizeQuote(r.text) };
});

/* Возвращает {found, t} — таймкод реплики, в которой цитата действительно есть */
function locateQuote(q) {
  if (!q) return { found: false, t: null };
  var n = normalizeQuote(q);
  if (!n) return { found: false, t: null };
  for (var i = 0; i < TRANSCRIPT_NORM.length; i++) {
    if (TRANSCRIPT_NORM[i].norm.indexOf(n) !== -1) return { found: true, t: TRANSCRIPT_NORM[i].t };
  }
  return { found: false, t: null };
}

/* Итоги — считаются, не вписываются руками */
function computeTotals(v) {
  var parts = SCORE_PARTS.map(function (p) { return { key: p.key, label: p.label, max: p.max, val: p.get(v) }; });
  var sum = parts.reduce(function (a, p) { return a + p.val; }, 0);
  var items = v.diagnostics.items;
  var collected = 0, missing = [], na = [], rejected = [];
  Object.keys(GATE_LABELS).forEach(function (k) {
    var it = items[k];
    /* Цитата есть, но в записи не найдена → вердикт по пункту НЕ принимается (правило промта),
       значит в зачёт гейта пункт не идёт: иначе балл стоял бы на выдуманном доказательстве. */
    var quoteRejected = !!(it && it.quote && !locateQuote(it.quote).found);
    if (it && it.asked && !quoteRejected) {
      collected++;
      if (it.value === 'N/A') na.push(k);
    } else {
      missing.push(k);
      if (quoteRejected) rejected.push(k);
    }
  });
  var quotes = { total: 0, ok: 0, bad: [] };
  function check(q, where) {
    if (!q) return;
    quotes.total++;
    var r = locateQuote(q);
    if (r.found) quotes.ok++; else quotes.bad.push({ where: where, quote: q });
  }
  Object.keys(items).forEach(function (k) { check(items[k].quote, 'гейт ' + GATE_LABELS[k].n); });
  Object.keys(LADDER_LABELS).forEach(function (k) { check(v.money_ladder[k].quote, 'лестница ' + LADDER_LABELS[k].n); });
  v.objections.items.forEach(function (o, i) { check(o.quote, 'возражение ' + (i + 1)); });
  v.empathy.quotes.forEach(function (q, i) { check(q, 'эмпатия ' + (i + 1)); });
  v.compliance_flags.forEach(function (f) { check(f.quote, 'комплаенс класс ' + f.class_id); });

  return {
    parts: parts,
    score: sum,
    scoreMismatch: sum !== v.score_total,
    collected: collected,
    missing: missing,
    na: na,
    rejected: rejected,
    gatePassed: collected === THRESHOLDS.gate_total,
    quotes: quotes
  };
}
